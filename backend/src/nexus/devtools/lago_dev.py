"""`uv run --project backend nexus-lago-dev [down]`: the Lago billing stack for development (D51, NEX-098).

Creates any missing Lago dev secret in the git-ignored `backend/.env` (random values, never printed), then starts
`compose.billing.yaml` and waits until the API is healthy. `down` stops it (data volumes are kept). Dev only.
"""

import base64
import secrets
import subprocess
import sys
from collections.abc import Callable
from pathlib import Path

import httpx2
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa

from nexus.core.timing import utf8_console
from nexus.settings import BACKEND_ROOT

ENV_FILE = Path(BACKEND_ROOT) / ".env"
COMPOSE = ["docker", "compose", "-f", str(Path(BACKEND_ROOT) / "compose.billing.yaml")]
WEBHOOK_KEY_VAR = "NEXUS_CONTROL_LAGO_WEBHOOK_KEY"
#: Where Lago delivers webhooks. Unset in dev: the dev Lago refuses private addresses
#: (`LAGO_WEBHOOK_ALLOW_PRIVATE_URLS=false`), so dev tests post bodies signed with the same key instead.
WEBHOOK_URL_VAR = "NEXUS_CONTROL_LAGO_WEBHOOK_URL"


def _rsa_pem_b64() -> str:
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    pem = key.private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.TraditionalOpenSSL, serialization.NoEncryption()
    )
    return base64.b64encode(pem).decode()


GENERATORS: dict[str, Callable[[], str]] = {
    "LAGO_DB_PASSWORD": lambda: secrets.token_urlsafe(24),
    "LAGO_SECRET_KEY_BASE": lambda: secrets.token_hex(64),
    "LAGO_RSA_PRIVATE_KEY": _rsa_pem_b64,
    "LAGO_ENCRYPTION_PRIMARY_KEY": lambda: secrets.token_hex(16),
    "LAGO_ENCRYPTION_DETERMINISTIC_KEY": lambda: secrets.token_hex(16),
    "LAGO_ENCRYPTION_KEY_DERIVATION_SALT": lambda: secrets.token_hex(16),
    "LAGO_ORG_USER_PASSWORD": lambda: secrets.token_urlsafe(24),
    "NEXUS_CONTROL_LAGO_API_KEY": lambda: secrets.token_hex(24),
}


def ensure_secrets(env_file: Path = ENV_FILE) -> list[str]:
    """Appends missing keys; returns their names (values are never printed)."""
    text = env_file.read_text(encoding="utf-8") if env_file.exists() else ""
    present = {line.split("=", 1)[0].strip() for line in text.splitlines() if "=" in line}
    missing = [k for k in GENERATORS if k not in present]
    if missing:
        lines = ["", "# Lago billing engine, dev only (NEX-098, generated by nexus-lago-dev)"]
        lines += [f"{k}={GENERATORS[k]()}" for k in missing]
        with env_file.open("a", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
    return missing


def _env_map(env_file: Path) -> dict[str, str]:
    if not env_file.exists():
        return {}
    out: dict[str, str] = {}
    for line in env_file.read_text(encoding="utf-8").splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def ensure_webhook(env_file: Path = ENV_FILE, lago_url: str = "http://127.0.0.1:53000") -> bool:
    """Writes Lago's HMAC webhook key to `.env` if missing; registers `NEXUS_CONTROL_LAGO_WEBHOOK_URL` when set."""
    env = _env_map(env_file)
    api_key = env.get("NEXUS_CONTROL_LAGO_API_KEY", "")
    if not api_key:
        return False
    if url := env.get(WEBHOOK_URL_VAR, ""):
        headers = {"Authorization": f"Bearer {api_key}"}
        with httpx2.Client(timeout=15) as http:
            res = http.get(f"{lago_url}/api/v1/webhook_endpoints", headers=headers)
            res.raise_for_status()
            endpoints = res.json().get("webhook_endpoints", [])
            if not any(e.get("webhook_url") == url and e.get("signature_algo") == "hmac" for e in endpoints):
                created = http.post(
                    f"{lago_url}/api/v1/webhook_endpoints",
                    headers=headers,
                    json={"webhook_endpoint": {"webhook_url": url, "signature_algo": "hmac"}},
                )
                created.raise_for_status()
    if env.get(WEBHOOK_KEY_VAR):
        return False
    cmd = [
        *COMPOSE,
        "--env-file",
        str(env_file),
        "exec",
        "-T",
        "lago-db",
        "psql",
        "-U",
        "lago",
        "-d",
        "lago",
        "-tAc",
        "SELECT hmac_key FROM organizations LIMIT 1",
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True, check=True)
    hmac_key = proc.stdout.strip()
    if not hmac_key:
        return False
    note = "# Lago webhook HMAC key, dev only (NEX-111, synced by nexus-lago-dev)"
    with env_file.open("a", encoding="utf-8", newline="\n") as f:
        f.write(f"\n{note}\n{WEBHOOK_KEY_VAR}={hmac_key}\n")
    return True


def main() -> None:
    utf8_console()
    if sys.argv[1:] == ["down"]:
        sys.exit(subprocess.run([*COMPOSE, "down"], check=False).returncode)
    added = ensure_secrets()
    if added:
        print(f"added to backend/.env: {', '.join(added)}")
    code = subprocess.run(
        [*COMPOSE, "--env-file", str(ENV_FILE), "up", "-d", "--wait", "--wait-timeout", "300"], check=False
    ).returncode
    if code == 0:
        wrote_key = ensure_webhook()
        if wrote_key:
            print(f"added to backend/.env: {WEBHOOK_KEY_VAR}")
        print("Lago API ready at http://127.0.0.1:53000 (key: NEXUS_CONTROL_LAGO_API_KEY in backend/.env)")
    sys.exit(code)


if __name__ == "__main__":
    main()
